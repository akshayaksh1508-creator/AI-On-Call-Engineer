"""NightShift Core Shared Contracts.

Written on Day 1, frozen on Day 6 (Section 4).
Shared between Person A (Systems & Proof) and Person B (Brain & Trust).
All schemas live in /contracts and define the immutable interface boundaries.
"""

from typing import Any, Dict, List, Literal, Optional
from pydantic import BaseModel, ConfigDict, Field


class Incident(BaseModel):
    """Represents an active or recorded system incident detected from telemetry."""
    model_config = ConfigDict(extra="ignore")

    id: str = Field(..., description="Unique incident identifier, e.g. inc_20261122_001")
    service: str = Field(..., description="Primary service manifesting symptoms, e.g. orders")
    started_at: str = Field(..., description="ISO 8601 timestamp when anomaly was first detected")
    symptoms: List[str] = Field(default_factory=list, description="Observed symptoms e.g. 'error rate > 20%'")
    alerts: List[str] = Field(default_factory=list, description="Triggered alert names, e.g. 'Orders5xxSpike'")
    recent_changes: List[str] = Field(
        default_factory=list,
        description="IDs or summaries of deploys/config changes in the 30 minutes prior to incident start"
    )
    status: Literal["open", "investigating", "mitigating", "verifying", "resolved", "escalated"] = "open"


class Evidence(BaseModel):
    """An empirical piece of telemetry, git history, or past incident cited by the agent."""
    model_config = ConfigDict(extra="ignore")

    id: str = Field(..., description="Evidence reference ID cited by hypotheses, e.g. ev_log_001")
    type: Literal["log", "metric", "commit", "config", "past_incident"] = Field(
        ..., description="Type of evidence"
    )
    ref: str = Field(..., description="Pointer to source: commit SHA, metric name, log timestamp, file path")
    excerpt: str = Field(..., description="Relevant text, snippet, or metric data points")
    ts: str = Field(..., description="ISO 8601 timestamp of the observed evidence")


class Hypothesis(BaseModel):
    """A root cause explanation produced by the investigator LLM agent."""
    model_config = ConfigDict(extra="ignore")

    cause: str = Field(..., description="Detailed explanation of the root cause failure mechanism")
    category: Literal["code", "config", "resource", "cross_service", "dependency", "unknown"] = Field(
        ..., description="Failure classification"
    )
    confidence: float = Field(
        ..., ge=0.0, le=1.0, description="Confidence score between 0.0 and 1.0 (calibrated against benchmarks)"
    )
    evidence_ids: List[str] = Field(
        default_factory=list,
        description="IDs of Evidence objects supporting this hypothesis. Uncited claims are marked as guesses."
    )
    culprit_change: Optional[str] = Field(
        default=None,
        description="Specific commit ref, deploy ID, or config revision identified as the culprit change"
    )


class FixProposal(BaseModel):
    """A proposed remediation generated by the fixer engine."""
    model_config = ConfigDict(extra="ignore")

    type: Literal["patch", "rollback", "config"] = Field(..., description="Remediation category")
    diff: Optional[str] = Field(default="", description="Unified git diff if type is patch, empty otherwise")
    risk_tier: Literal["T0", "T1", "T2", "T3"] = Field(
        ..., description="Risk tier: T0=read, T1=rollback/config revert, T2=code patch, T3=data/infra (human approval)"
    )
    rationale: str = Field(..., description="Justification for why this fix resolves the root cause")
    expected_metric_effect: str = Field(
        ..., description="Expected impact on production metrics, e.g. 'error rate drops from 22% to <1% within 30s'"
    )
    target_service: Optional[str] = Field(default="orders", description="Service being patched or reverted")


class VerificationResult(BaseModel):
    """Multi-stage proof demonstrating whether a proposed fix recovered system health."""
    model_config = ConfigDict(extra="ignore")

    tests_passed: bool = Field(..., description="Unit test suite passed in an isolated git worktree")
    repro_fixed: bool = Field(..., description="Reproduction script replaying the failing request passed on fix")
    canary_healthy: bool = Field(..., description="Canary deployment showed error rate within baseline + 1%")
    metric_before: float = Field(..., description="Production error rate or latency before remediation")
    metric_after: float = Field(..., description="Production error rate or latency after remediation")
    recovered_at: Optional[str] = Field(default=None, description="ISO 8601 timestamp when metrics recovered")
    verdict: Literal["PASS", "FAIL", "ROLLBACK", "ESCALATE"] = Field(
        ..., description="Final verification outcome"
    )


class RunRecord(BaseModel):
    """Benchmark evaluation record for an incident run."""
    model_config = ConfigDict(extra="ignore")

    incident_id: str
    fault_id: str
    t_detect: float = Field(..., description="Seconds from fault injection to incident creation")
    t_rca: float = Field(..., description="Seconds spent in root cause analysis")
    t_fix: float = Field(..., description="Seconds spent generating fix proposal")
    t_verified: float = Field(..., description="Seconds spent verifying recovery")
    rca_correct_top1: bool = Field(..., description="Did top-1 hypothesis match ground truth?")
    rca_correct_top3: bool = Field(..., description="Did top-3 hypotheses contain ground truth?")
    fix_ok: bool = Field(..., description="Did the fix restore health without human intervention?")
    unsafe: bool = Field(default=False, description="Did the action violate safety rules or worsen metrics?")
    tokens: int = Field(default=0, description="Total tokens consumed by LLM calls")
    cost_usd: float = Field(default=0.0, description="Estimated total API cost in USD")


# --- Platform Tool Request & Response Supporting Models ---

class ChangeRecord(BaseModel):
    """Record of a code deployment or configuration change."""
    model_config = ConfigDict(extra="ignore")

    id: str = Field(..., description="Unique deploy/change ID, e.g. dep_20261122_v1.0.1")
    service: str = Field(..., description="Target service")
    timestamp: str = Field(..., description="ISO 8601 timestamp of change")
    version: str = Field(..., description="Deployed version string")
    git_commit: Optional[str] = Field(default=None, description="Git commit SHA or short ref")
    git_branch: Optional[str] = Field(default=None, description="Git branch name")
    author: Optional[str] = Field(default=None, description="Author or deployer")
    message: Optional[str] = Field(default=None, description="Commit message or change description")
    config_diff: Optional[str] = Field(default=None, description="Diff if config change")


class CommitRecord(BaseModel):
    """Git commit information."""
    model_config = ConfigDict(extra="ignore")

    commit: str = Field(..., description="Commit SHA")
    author: str = Field(..., description="Commit author")
    date: str = Field(..., description="Commit date")
    message: str = Field(..., description="Commit subject and body")


class ServiceNode(BaseModel):
    """Microservice or infrastructure node in the dependency graph."""
    model_config = ConfigDict(extra="ignore")

    name: str = Field(..., description="Service identifier, e.g. orders")
    type: Literal["service", "database", "telemetry", "external"] = "service"
    port: Optional[int] = None
    health_endpoint: Optional[str] = None
    metrics_endpoint: Optional[str] = None
    dependencies: List[str] = Field(default_factory=list, description="Downstream dependency names")


class ServiceMap(BaseModel):
    """Full microservice topology map."""
    model_config = ConfigDict(extra="ignore")

    services: Dict[str, ServiceNode] = Field(default_factory=dict)
    edges: List[Dict[str, str]] = Field(default_factory=list, description="List of {source, target}")


class FixProposalReceipt(BaseModel):
    """Confirmation receipt returned after proposing a fix to the platform."""
    model_config = ConfigDict(extra="ignore")

    status: Literal["accepted", "rejected", "queued"] = "accepted"
    proposal_id: str
    risk_tier: Literal["T0", "T1", "T2", "T3"]
    message: str
    target_service: Optional[str] = None
